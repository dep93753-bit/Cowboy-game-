"""Turn the Mucho Pixels character pack frames into js/charframes.js.

Each frame becomes rows of letters, one letter per colour *role* (outline,
skin, hair, shirt, pants, shoes...), so the game can repaint them with any
skin tone, hair colour or outfit at load time (works from file:// too).

usage: python3 -I tools/pack_chars.py "<path to Exported PNGs>"
"""
import json, os, sys
from PIL import Image

SRC = sys.argv[1]
BODIES = {'m': 'Male/Character 1/Clothes 1/Character1M_1', 'f': 'Female/Character 1/Clothes 1/Character1F_1'}
ANIMS = {'idle': None, 'walk': None, 'run': None, 'punch': None, 'jump': None, 'fall': None,
         'land': None, 'damage': [1], 'death': None}
# pack colour -> role letter
ROLE = {
    (14, 7, 27): 'A',                                      # outline
    (230, 156, 105): 'S', (191, 111, 74): 's',             # skin, skin shade
    (138, 72, 54): 'H', (93, 44, 40): 'h',                 # hair, hair shade
    (234, 50, 60): 'T', (196, 36, 48): 't', (137, 30, 43): 'u',  # shirt
    (0, 152, 220): 'P', (0, 105, 170): 'p',                # pants
    (199, 207, 221): 'B', (146, 161, 185): 'b',            # shoes
}
def split_hair(rows):
    # The pack paints hair and the deepest skin shade the same brown. Hair is
    # whatever 'H' touches the dark hair shade 'h'; any other 'H' is skin 'k'.
    g = [list(r) for r in rows]
    seen, stack = set(), [(x, y) for y, r in enumerate(g) for x, c in enumerate(r) if c == 'h']
    while stack:
        x, y = stack.pop()
        if (x, y) in seen: continue
        seen.add((x, y))
        for nx, ny in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
            if 0 <= ny < len(g) and 0 <= nx < len(g[ny]) and g[ny][nx] in 'Hh': stack.append((nx, ny))
    for y, r in enumerate(g):
        for x, c in enumerate(r):
            if c == 'H' and (x, y) not in seen: r[x] = 'k'
    return [''.join(r) for r in g]

CROP = (14, 8, 58, 48)   # 44x40 box around the body, feet on the last row

out, unknown = {}, set()
for g, prefix in BODIES.items():
    out[g] = {}
    for anim, pick in ANIMS.items():
        frames, i = [], 0
        while os.path.exists(f'{SRC}/{prefix}_{anim}_{i}.png'):
            if pick is None or i in pick:
                im = Image.open(f'{SRC}/{prefix}_{anim}_{i}.png').convert('RGBA').crop(CROP)
                px = im.load()
                rows = []
                for y in range(im.height):
                    r = ''
                    for x in range(im.width):
                        c = px[x, y]
                        if c[3] < 128: r += '.'
                        elif c[:3] in ROLE: r += ROLE[c[:3]]
                        else: unknown.add(c[:3]); r += '.'
                    rows.append(r)
                frames.append(split_hair(rows))
            i += 1
        out[g][anim] = frames
if unknown: print('unmapped colours:', unknown, file=sys.stderr)

with open(os.path.join(os.path.dirname(__file__), '..', 'js', 'charframes.js'), 'w') as f:
    f.write('// Generated by tools/pack_chars.py from the Mucho Pixels Character Animation\n')
    f.write('// Asset Pack. One letter per colour role; see js/chars.js for the palette.\n')
    f.write('const CHAR_FRAMES = ' + json.dumps(out, separators=(',', ':')) + ';\n')
print({g: {a: len(v) for a, v in d.items()} for g, d in out.items()})
